"""Shikumi 文書体系で使用する正本 Vocabulary の記述体。

``TERM_N`` の数値部分は Python 上で各記述単位を識別するためだけに存在し、
順序、分類、用語名その他の意味を一切表さない。
"""

from shikumi_devdoc.norms.vocabulary import canonical, glossary, preserve_spelling, term, title


@canonical
@title("Shikumi 用語集")
class VOCABULARY:
    """Shikumi における正規の用語と、その意味上の境界を定義する。"""

    @term("Shikumi")
    class TERM_1:
        """Python 上の対象を、構造と情報に基づく一つの意味体系として解釈する構成単位。

        Shikumi は、解釈対象から意味像を構成し、その意味像を検証や実現から利用できる形で提供する。
        """

        preserve_spelling @= True

        glossary @= True


    @term("規定")
    class TERM_2:
        """Shikumi において、構造、情報型、記述器、記述器使用規則、検証規則など、対象をどのように記述し解釈するかを定めること、および定められた内容。

        規定は、記述の具体的な内容ではなく、その記述を意味情報として成立させるための規則と形式を定める。
        """

        glossary @= True


    @term("規定体")
    class TERM_3:
        """規定を Python コードとして具体的に記述した `package` または `module`。

        規定体は、構造、情報型、記述器、記述器使用規則、検証規則など、Shikumi の規定を構成する定義を含み得る。
        """

        glossary @= True


    @term("記述")
    class TERM_4:
        """規定に従い、Python コード上で解釈対象または実体に意味情報を与えること、およびその内容。

        記述は、記述器その他の実行時の処理を通じて情報として成立する。
        """

        glossary @= True


    @term("記述体")
    class TERM_5:
        """記述を含む Python の `package` または `module`。

        記述体は、情報が記述された実体を含み、Shikumi による解釈の素材および焦点となり得る。
        """

        glossary @= True


    @term("解釈対象")
    class TERM_6:
        """Shikumi が解釈する対象。

        Python の `package`、`module`、`class` などの実行時の対象、および構造の解釈に必要なファイル配置を含み得る。
        """

        glossary @= True


    @term("構造")
    class TERM_7:
        """解釈対象に含まれる要素の配置、包含関係、位置関係を表すもの。

        構造は、`package`、`module`、実体などが意味体系の中でどこに位置するかを定める。
        """

        glossary @= True


    @term("構造規定")
    class TERM_8:
        """焦点から見た `package`、`module`、実体の相対的な配置と包含関係について、満たすべき構造を定める規定。

        構造規定は、規定体が構造上の位置と種類を明示的に定義して成立させることも、ある記述体を構造として解釈した結果から導出して成立させることもできる。どちらを用いるかは利用者が明示し、Shikumi は一方が存在しない場合に他方を推論または代用しない。

        構造規定に対する検証では、焦点に対応する構造上の範囲について位置と種類の一致を要求する。`module` などを全体の一部分として単独に検証する場合は、その対象を構造上のどこに配置する予定であるかを明示し、その配置に対応する部分構造を検証する。

        構造規定は、実体に接続された情報の内容、使用された記述器、その記述方法や import 元の一致を要求しない。記述器を使用できる構造上の位置に条件が必要な場合は記述器使用規則として、情報の内容に条件が必要な場合は情報型や検証規則として、構造規定とは別に定める。
        """

        glossary @= True


    @term("物理構造")
    class TERM_9:
        """ファイル配置と Python の `package` / `module` の実際の配置によって表される構造。

        ディレクトリ、ファイル、`package`、`module` などの物理的な位置関係を扱う。
        """

        glossary @= True


    @term("意味構造")
    class TERM_10:
        """Shikumi が解釈対象を解釈した結果として成立する意味上の構造。

        意味構造は、Shikumi が `package`、`module`、実体などをどの位置関係として認識するかを表す。
        """

        glossary @= True


    @term("実体")
    class TERM_11:
        """意味構造上で、個別に情報を持つ対象として扱われる単位。

        Python の `class` などの実行時の対象が実体として解釈され得る。何を実体とみなすかは構造によって定まる。
        """

        glossary @= True


    @term("情報型")
    class TERM_12:
        """Shikumi が扱う意味情報の型。

        情報型は、値の型、個数など、その情報が持つ意味上の性質を定義する。Python 上での記述方法は含まない。
        """

        glossary @= True


    @term("情報")
    class TERM_13:
        """解釈対象または実体に記録された一件の意味情報。

        情報は情報型、値、および接続先となる対象を持つ。記述器の使用事実は情報そのものには含めず、記述器使用として別に扱う。
        """

        glossary @= True


    @term("情報接続")
    class TERM_14:
        """記述によって得られた値や状態を、情報として解釈対象または実体に関連付け、Shikumi から認識可能な状態にすること。

        どの値を、どの情報型の情報として、どの対象へ接続するかは規定側で定める。記述器は情報接続を通じて記述を実行時の情報として成立させる。

        記述時点で接続先となる実体がまだ成立していない場合、実体の成立後まで情報接続の処理を遅らせることができる。遅延の具体的な方法は情報接続の実装に属する。
        """

        glossary @= True


    @term("記述器")
    class TERM_15:
        """Python コード上の記述を情報として成立させるための、規定側の仕組み。

        記述器は、`@=`、デコレータ、docstring その他の任意の記述形式を用いることができる。記述形式、引数、値の構成方法は記述器の定義によって定まり、Shikumi はその具体形を規定しない。

        記述器は情報接続を用いて、記述によって得られた情報を解釈対象または実体へ接続できる。規定は、記述器の具体的な記述形式や情報の値とは独立に、その記述器を使用可能または推奨とする構造上の位置を定めることができる。
        """

        glossary @= True


    @term("記述器使用")
    class TERM_16:
        """ある記述器が、ある解釈対象または実体に対して使用されたという実行時の事実。

        記述器使用は、記述器が接続した情報そのものとは区別される。一回の記述器使用から複数の情報接続が行われてもよく、記述器使用を伴わずに情報接続が直接行われてもよい。

        記述器使用は、記述器の import 元やソースコード上の表記を追跡するものではない。Shikumi は Python の実行後に成立した記述器使用を、構造上の位置との関係を検証するための意味状態として扱う。
        """

        glossary @= True


    @term("記述器使用規則")
    class TERM_17:
        """ある記述器を、意味構造上のどの位置で使用可能または推奨とするかを定める規定。

        記述器使用規則は、記述器が生成または接続する情報の内容を定めるものではない。記述器使用と、その使用対象の構造上の位置との関係を評価し、使用不可の位置での使用や、使用可能だが推奨されない位置での使用を診断情報として報告できる。

        記述器使用規則が定められていない記述器は、この規則による構造上の制約を受けない。その扱いを情報内容や import 元から推論しない。
        """

        glossary @= True


    @term("解釈")
    class TERM_18:
        """Shikumi が解釈対象を構造、情報、記述器使用の観点から読み取り、意味像を構成する処理。

        解釈は Python の実行によって成立した対象、情報、記述器使用を扱う。
        """

        glossary @= True


    @term("意味像")
    class TERM_19:
        """Shikumi が特定の焦点について解釈して得る、意味上の観測結果。

        意味像は、焦点を中心に、構造、実体、情報、記述器使用、索引など、検証や実現が利用する意味情報を提供する。

        情報の値として別の実体、`module`、関数その他の Python オブジェクトを保持しても、それ自体に Shikumi 固有の参照意味は与えられない。その値をどのように解釈し利用するかは規定側で定める。
        """

        glossary @= True


    @term("焦点")
    class TERM_20:
        """Shikumi が一つの意味像を構成するとき、意味的な中心として据える位置または構造上の単位。

        実体、`module`、`package`、ディレクトリなどを焦点とすることができる。意味像は焦点を中心として構成され、どこまでの構造や情報を含むかは、構造と処理の性質によって定まる。

        焦点は、必要に応じて対象の構造上の配置を伴う。特に `module` を単独で検証するときは、現在の import 名から配置を推論せず、どこに配置する予定の `module` として検証するかを明示する。
        """

        glossary @= True


    @term("検証")
    class TERM_21:
        """意味像が定められた条件を満たしているかを調べる処理。

        検証は Python の実行によって成立した意味状態を対象とする。
        """

        glossary @= True


    @term("検証規則")
    class TERM_22:
        """検証を構成する個々の規則。

        検証規則は、評価に必要な焦点と、その焦点について構成された意味像に対する条件を定める。
        """

        glossary @= True


    @term("診断情報")
    class TERM_23:
        """検証などによって観測された問題または状態を、利用者へ報告可能な形で表した情報。

        診断情報は、識別子、重大度、対象、説明などを持ち得る。
        """

        glossary @= True


    @term("不変条件")
    class TERM_24:
        """Shikumi の意味体系または実行機構が成立するために、常に満たされなければならない条件。

        不変条件が満たされない状態は、通常の検証における不適合とは区別される。
        """

        glossary @= True


    @term("実現")
    class TERM_25:
        """意味像を成果物へ変換する処理。"""

        glossary @= True


    @term("実現器")
    class TERM_26:
        """意味像を読み取り、成果物を生成するもの。

        実現器は情報と構造の意味表現を利用する。実現器は規定体や Shikumi に所属せず、独立して成立する。同一の意味像に複数の実現器を適用できる。

        実現器は、成果物を生成せずに、与えられた意味像を自身が実現可能か問い合わせる手段を提供する。
        """

        glossary @= True


    @term("実現可能性")
    class TERM_27:
        """特定の実現器が、与えられた意味像から成果物を生成できるかを表す性質。

        実現可能性は規定への適合性とは独立している。記述体が規定および構造規定を満たしていても、特定の実現器が必要とする情報や条件を満たさず、実現不可能である場合がある。実現可能性の判定は成果物を生成せずに行う。
        """

        glossary @= True


    @term("成果物")
    class TERM_28:
        """実現によって生成される結果。

        成果物は Markdown、HTML、JSON、グラフ、文字列、その他の Python の値などの形式を取り得る。
        """

        glossary @= True


    @term("実行時確定原則")
    class TERM_29:
        """Shikumi の意味状態を、Python の実行後に成立した状態に基づいて確定する原則。

        記述器、デコレータ、`@=`、関数呼び出し、`import` などの実行結果として成立した Python の対象、情報、記述器使用が解釈の入力となる。
        """

        glossary @= True


    @term("shikumi_lib")
    class TERM_33:
        """プロジェクト固有の Shikumi 関連コードをまとめる package の推奨名。"""

        preserve_spelling @= True


    @term("norms")
    class TERM_34:
        """`shikumi_lib` 内で、規定体としての役割を担うコードをまとめる subpackage の推奨名。"""

        preserve_spelling @= True


    @term("realizers")
    class TERM_35:
        """`shikumi_lib` 内で、実現器をまとめる subpackage の推奨名。"""

        preserve_spelling @= True
